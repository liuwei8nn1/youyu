/**
 * Gateway Service - 网关服务架构说明
 * <p>
 * ========================================
 * 📦 包结构说明
 * ========================================
 * <p>
 * gateway/
 * ├── config/                        # 配置类（基础设施层）
 * │   ├── GatewayConfig.java         # 网关路由配置
 * │   └── GatewayI18nConfig.java     # 国际化配置
 * │
 * ├── filter/                        # 过滤器（接口层 - 网关特有）
 * │   └── JwtFilter.java             # JWT认证过滤器
 * │
 * ├── enums/                         # 枚举（领域层）
 * │   ├── UserType.java              # 用户类型枚举
 * │   └── PermissionLevel.java       # 权限级别枚举
 * │
 * ├── util/                          # 工具类（基础设施层）
 * │   └── JwtUtil.java               # JWT工具类
 * │
 * └── interfaces/                    # 用户接口层（预留扩展）
 *     └── ...                        # 未来可扩展 Controller、Handler 等
 * <p>
 * ========================================
 * 🔄 网关特殊说明
 * ========================================
 * <p>
 * 网关服务不同于业务微服务，不采用标准的 DDD 四层架构。
 * 原因：
 * 1. 网关是基础设施层服务，不是业务领域服务
 * 2. 主要职责是路由转发、认证授权、限流熔断
 * 3. 不包含复杂的业务逻辑和领域模型
 * <p>
 * ========================================
 * 📝 各模块职责
 * ========================================
 * <p>
 * 【配置模块 - config】（基础设施层）
 * - 网关路由配置（Nacos 动态路由）
 * - 安全配置（JWT 验证、白名单）
 * - Redis 配置（限流、会话管理）
 * <p>
 * 【过滤器模块 - filter】（接口层 - 网关特有）
 * - JWT 认证过滤器：验证 Token、检查用户状态、传递用户信息
 * - 所有过滤器按顺序执行，形成责任链
 * - 过滤器作为网关的入口点，相当于传统应用的 Controller
 * <p>
 * 【枚举模块 - enums】（领域层）
 * - UserType：定义用户类型（普通用户、员工、管理员）
 * - PermissionLevel：定义权限级别和权限检查逻辑
 * - 这些枚举包含业务规则，属于领域层
 * <p>
 * 【工具模块 - util】（基础设施层）
 * - JwtUtil：JWT Token 解析和用户信息提取
 * - 纯技术实现，不包含业务逻辑
 * <p>
 * ========================================
 * ⚠️ 注意事项
 * ========================================
 * <p>
 * 1. 网关不实现业务逻辑，只做路由和过滤
 * 2. 认证信息通过请求头传递给下游服务（X-User-Id, X-User-Type）
 * 3. 限流使用 Redis Pipeline 提高性能
 * 4. 路由配置从 Nacos 动态加载，支持热更新
 * 5. 网关是多实例部署，需要使用 Redis Pub/Sub 同步会话状态
 * 6. 如需扩展新功能，建议在 interfaces 包下添加 Controller 或 Handler
 * 
 * @since 2026/4/18
 */
